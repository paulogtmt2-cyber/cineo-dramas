-- Run only as a single transaction; every fixture is rolled back.
begin;
do $$declare actor uuid;owner uuid;sid bigint;eid bigint;session uuid;other uuid;r jsonb;n integer;begin
 select user_id into actor from public.cineo_admins limit 1;
 select s.owner_id,s.id,e.id into owner,sid,eid from public.cineo_shows s join public.cineo_episodes e on e.show_id=s.id where s.owner_id<>actor and s.status='approved' and not s.hidden and e.review_status='approved' and not e.hidden limit 1;
 if owner is null then raise exception 'A public fixture owned by another account is required';end if;
 if exists(select 1 from public.cineo_creator_accounts where user_id=owner) then raise exception 'Choose a fixture without an enrollment';end if;
 insert into public.cineo_creator_accounts(user_id,first_name,last_name,birth_date) values(owner,'Fixture','Private','1990-01-01');
 r:=public.cineo_creator_transition(owner,null,'auto','');
 if r->>'status'<>'pending' then raise exception 'Approval occurred before server deadline';end if;
 update public.cineo_creator_accounts set eligible_at=now()-interval '1 second' where user_id=owner;
 r:=public.cineo_creator_transition(owner,null,'auto','');
 if r->>'status'<>'approved' then raise exception 'Due approval failed';end if;
 if r ? 'selfie_path' then raise exception 'Private storage path leaked';end if;
 begin perform public.cineo_creator_transition(owner,owner,'ban','Not the administrator');raise exception 'UNAUTHORIZED_BAN';exception when others then if sqlerrm='UNAUTHORIZED_BAN' then raise;end if;end;
 insert into public.cineo_view_sessions(user_id,episode_id,last_at) values(actor,eid,now()-interval '20 seconds') returning id into session;
 r:=public.cineo_view_heartbeat(actor,session,500000,0);
 if r->>'credited'='true' then raise exception 'Seek without active playback was credited';end if;
 update public.cineo_view_sessions set last_at=now()-interval '20 seconds',position_ms=0,reported_ms=0 where id=session;
 r:=public.cineo_view_heartbeat(actor,session,10000,10000);
 if r->>'new_view'<>'true' then raise exception 'Qualified playback missing';end if;
 begin perform public.cineo_view_heartbeat(owner,session,12000,12000);raise exception 'CROSS_ACCOUNT_SESSION';exception when others then if sqlerrm='CROSS_ACCOUNT_SESSION' then raise;end if;end;
 insert into public.cineo_view_sessions(user_id,episode_id,last_at) values(actor,eid,now()-interval '20 seconds') returning id into other;
 r:=public.cineo_view_heartbeat(actor,other,10000,10000);
 if r->>'new_view'<>'false' then raise exception 'Duplicate daily view credited';end if;
 select count(*) into n from public.cineo_qualified_views where user_id=actor and episode_id=eid;
 if n<>1 then raise exception 'Daily uniqueness violated';end if;
 r:=public.cineo_creator_metrics(owner);
 if (r->>'estimated_cents')::numeric<>0.04 then raise exception 'Rate must be 40 cents per thousand, not 40 cents per view';end if;
 r:=public.cineo_creator_transition(owner,actor,'ban','Fixture ban reason');
 r:=public.cineo_creator_transition(owner,null,'auto','');
 if r->>'status'<>'banned' then raise exception 'Auto approval bypassed ban';end if;
 r:=public.cineo_creator_transition(owner,actor,'restore','Fixture restoration');
 if r->>'status'<>'approved' then raise exception 'Admin restoration failed';end if;
 insert into public.cineo_view_sessions(user_id,episode_id,last_at) values(owner,eid,now()-interval '20 seconds') returning id into session;
 r:=public.cineo_view_heartbeat(owner,session,10000,10000);
 if r->>'credited'='true' then raise exception 'Own views must be excluded';end if;
end$$;
select 'Creator transition, ownership, elapsed playback, seeking, daily uniqueness, earnings rate and ban tests passed; fixtures rolled back' as result;
rollback;
